@strawberry.type
class Order:
    order_id: int
    order_date: datetime
    status: str
    payment_method: str
    shipping_city: str
    shipping_state: str
    shipping_country: str
    processing_date: datetime | None
    shipping_date: datetime | None
    delivery_date: datetime | None
    total_amount: Decimal

    customer_id: strawberry.Private[int]

    @classmethod
    def from_row(cls, row: dict[str, Any]) -> Order:
        return cls(
            order_id=row["order_id"],
            order_date=row["order_date"],
            status=row["status"],
            payment_method=row["payment_method"],
            shipping_city=row["shipping_city"],
            shipping_state=row["shipping_state"],
            shipping_country=row["shipping_country"],
            processing_date=row.get("processing_date"),
            shipping_date=row.get("shipping_date"),
            delivery_date=row.get("delivery_date"),
            total_amount=row["total_amount"],
            customer_id=row["customer_id"],
        )

    @strawberry.field(description="Line items, batched by (order_id, order_date).")
    async def items(self, info: strawberry.Info) -> list[OrderItem]:
        rows = await info.context["loaders"].order_items.load(
            (self.order_id, self.order_date)
        )
        return [OrderItem.from_row(row) for row in rows]

    @strawberry.field(description="Batched through a DataLoader.")
    async def customer(self, info: strawberry.Info) -> Customer | None:
        row = await info.context["loaders"].customer.load(self.customer_id)
        return Customer.from_row(row) if row else None


