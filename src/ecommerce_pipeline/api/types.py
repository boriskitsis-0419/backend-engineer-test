@strawberry.type
class Category:
    category_id: int
    name: str
    description: str | None
    parent_id: int | None

    @classmethod
    def from_row(cls, row: dict[str, Any]) -> Category:
        return cls(
            category_id=row["category_id"],
            name=row["name"],
            description=row.get("description"),
            parent_id=row.get("parent_id"),
        )


@strawberry.type
class Product:
    product_id: int
    name: str
    description: str | None
    price: Decimal
    cost: Decimal | None
    sku: str
    inventory_count: int
    weight: Decimal | None
    is_active: bool
    created_at: datetime
    updated_at: datetime

    # Kept private so `category` can be resolved through a DataLoader instead
    # of being fetched eagerly for every product in a page.
    category_id: strawberry.Private[int]

    @classmethod
    def from_row(cls, row: dict[str, Any]) -> Product:
        return cls(
            product_id=row["product_id"],
            name=row["name"],
            description=row.get("description"),
            price=row["price"],
            cost=row.get("cost"),
            sku=row["sku"],
            inventory_count=row["inventory_count"],
            weight=row.get("weight"),
            is_active=row["is_active"],
            created_at=row["created_at"],
            updated_at=row["updated_at"],
            category_id=row["category_id"],
        )

    @strawberry.field(description="Batched through a DataLoader.")
    async def category(self, info: strawberry.Info) -> Category | None:
        row = await info.context["loaders"].category.load(self.category_id)
        return Category.from_row(row) if row else None


